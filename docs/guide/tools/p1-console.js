const fs = require('fs');
const { launch, shot, local, CONSOLE, TENANT, OUT } = require('./lib');
const LOGO = require('path').join(__dirname, '../../tenants/al-musabbihin/logo.png');
(async () => {
  const b = await launch();
  const p = await b.newPage({ viewport: { width: 1440, height: 900 } });
  const errors = []; p.on('pageerror', (e) => errors.push(e.message));
  await p.goto(local(CONSOLE, '/console'));
  await p.locator('#console-email').waitFor();
  await shot(p, '01-console-login');
  await p.fill('#console-email', 'ops@nexoratech.co');
  await p.fill('#console-password', 'Console-Docs-2026');
  await p.click('button[type=submit]');
  await p.getByRole('heading', { name: 'Sekolah (tenant)' }).waitFor();
  await shot(p, '02-console-list-empty');
  await p.getByRole('button', { name: /Tenant baru/ }).click();
  await p.locator('#tw-name').waitFor();
  await p.fill('#tw-name', 'Sekolah Islam Terpadu Al Musabbihin');
  await p.fill('#tw-short', 'SIT Al Musabbihin');
  await p.fill('#tw-slug', 'al-musabbihin');
  await p.fill('#tw-city', 'Bandung');
  await p.fill('#tw-address', 'Jl. Contoh Pendidikan No. 1, Bandung');
  await p.fill('#tw-npsn', '20200001');
  for (const [id, v] of [['#tw-headmaster', 'Ust. Ahmad Fauzi, S.Pd.I'], ['#tw-treasurer', 'Siti Rahmawati, S.E.']]) {
    if (await p.locator(id).count()) await p.fill(id, v);
  }
  await shot(p, '03-console-wizard-identity');
  await p.getByRole('button', { name: 'Lanjut' }).click();
  await p.setInputFiles('#tw-logo', LOGO);
  await p.getByText('dari logo').waitFor();
  await p.waitForTimeout(600);
  await shot(p, '04-console-wizard-logo-palette');
  await p.getByRole('button', { name: 'Lanjut' }).click();
  await p.locator('#tw-admin').waitFor();
  await p.fill('#tw-admin', 'admin-almusabbihin');
  await p.fill('#tw-admin-name', 'Administrator Al Musabbihin');
  await p.fill('#tw-admin-email', 'admin@al-musabbihin.sch.id');
  await shot(p, '05-console-wizard-admin-domain');
  await p.getByRole('button', { name: /Buat tenant/ }).click();
  await p.getByText(/siap digunakan/).waitFor();
  const codes = await p.locator('dd code').allTextContents();
  const temp = codes.map((c) => c.trim()).find((c) => c.length >= 12 && !c.includes('.') && !c.includes('admin'));
  fs.writeFileSync(`${OUT}/.temp-pass`, temp);
  await shot(p, '06-console-created', { mask: ['dd code >> nth=2'] });
  await p.getByRole('button', { name: 'Kelola tenant' }).click();
  await p.locator('#td-name').waitFor();
  await p.waitForTimeout(800);
  await shot(p, '07-console-tenant-detail', { full: true });
  await p.goto(local(CONSOLE, '/console'));
  await p.getByRole('heading', { name: 'Sekolah (tenant)' }).waitFor();
  await p.waitForTimeout(500);
  await shot(p, '08-console-list');
  console.log('temp len', temp && temp.length, 'errors', errors);
  await b.close();
})().catch((e) => { console.error(e); process.exit(1); });
